/**
 * Build the shipped Client half.
 *
 * The Harness loads a plugin's browser artifact through
 * `window.__ModuleLoader__.load({ id, factory })`, and the factory receives a
 * CommonJS-shaped `require` that only resolves the runtime modules the host
 * exposes (`react`). It does not resolve relative paths, and there is no ESM
 * pipeline for bundle files, so `plugin/client.js` has to arrive as one
 * self-contained script.
 *
 * This script concatenates the plain-ESM sources under `src/` into that single
 * script. The transformation is deliberately dumb and auditable:
 *
 *   - `import ... from '...';` statements are dropped (the bundle is ordered by
 *     hand in MODULES instead, and the names are unique across modules);
 *   - a leading `export ` keyword is stripped from declaration lines;
 *   - everything else is copied verbatim.
 *
 * `src/client/main.js` is the last module: it defines `applyClient(ctx)`, and
 * the wrapper below registers it with the loader.
 *
 *   node build/bundle-client.mjs
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const OUT_DIR = resolve(REPO, 'plugin');
const OUT_FILE = resolve(OUT_DIR, 'client.js');

/** Order matters: later modules may read names declared by earlier ones. */
const MODULES = [
  'src/generated/palettes.js',
  'src/parts/palette-spec.js',
  'src/parts/token-map.js',
  'src/client/stylesheet.js',
  'src/client/main.js',
];

const PACKAGE_ID = 'dsh-stars-material';

const IMPORT_LINE = /^\s*import\s[\s\S]*?;\s*$/u;
const EXPORT_DECL = /^export\s+(?=(?:const|let|var|function|class|async)\b)/u;
const EXPORT_LIST = /^export\s*\{[^}]*\}\s*;?\s*$/u;

function stripModule(source, path) {
  const out = [];
  const lines = source.split('\n');
  let skippingImport = false;

  for (const line of lines) {
    if (skippingImport) {
      if (line.includes(';')) skippingImport = false;
      continue;
    }
    // Single-line imports are the only form used in this repository; the guard
    // keeps a stray multi-line import from silently leaking `import` into the
    // bundle, where it would be a syntax error at load time.
    if (IMPORT_LINE.test(line)) {
      if (!line.includes(';')) skippingImport = true;
      continue;
    }
    if (line.includes('import ') && /^\s*import\b/u.test(line)) {
      throw new Error(`${path}: multi-line import is not supported by this bundler`);
    }
    if (EXPORT_LIST.test(line)) continue;
    out.push(line.replace(EXPORT_DECL, ''));
  }

  const body = out.join('\n');
  if (/^\s*(?:import|export)\b/mu.test(body)) {
    throw new Error(`${path}: leftover import/export after stripping`);
  }
  return body.trim();
}

const parts = [];
for (const modulePath of MODULES) {
  const absolute = resolve(REPO, modulePath);
  const source = await readFile(absolute, 'utf8');
  parts.push(`/* ---- ${relative(REPO, absolute).replaceAll('\\', '/')} ---- */\n${stripModule(source, modulePath)}`);
}

const wrapper = `/* Generated by build/bundle-client.mjs — do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE_ID)},
  factory: (require) => {
    'use strict';

    const React = require('react');
    const h = React.createElement;

${parts.join('\n\n')}

    return {
      inject: ['slots', 'locale', 'theme'],
      apply: applyClient,
    };
  },
});
`;

await mkdir(OUT_DIR, { recursive: true });
await writeFile(OUT_FILE, wrapper, 'utf8');

// Fail the build rather than ship a script the browser cannot parse.
try {
  // eslint-disable-next-line no-new-func
  new Function(wrapper);
} catch (error) {
  throw new Error(`generated client.js does not parse: ${error.message}`);
}

for (const required of ['window.__ModuleLoader__.load', 'applyClient', 'buildTokenMap']) {
  if (!wrapper.includes(required)) {
    throw new Error(`generated client.js is missing "${required}"`);
  }
}

const bytes = Buffer.byteLength(wrapper, 'utf8');
console.log(`wrote ${OUT_FILE} (${bytes} bytes)`);
console.log(`modules=${MODULES.length} parses=ok`);
