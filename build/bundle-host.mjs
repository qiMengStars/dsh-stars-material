/**
 * Build the Host-side palette library.
 *
 *   node build/bundle-host.mjs
 *
 * The Host half needs two things the Client half must not have: the Material
 * Color Utilities implementation (to derive a palette from the OS accent colour)
 * and the palette engine. Both are copied into `plugin/lib/` so the published
 * bundle carries its own dependencies and installs with no `node_modules`.
 *
 * Unlike `build/bundle-client.mjs`, nothing here is concatenated: the Host half
 * is a normal Node ESM module graph, so `import` works and each file keeps its
 * own scope.
 *
 * Output:
 *   plugin/lib/mcu/index.js      the vendored library entry point
 *   plugin/lib/mcu/**            the rest of the library, `.js` imports intact
 *   plugin/lib/palette.js        engine + role table + MCU, one module
 *   plugin/lib/mcu/LICENSE       Apache-2.0, required to redistribute
 */

import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const VENDOR = resolve(REPO, 'vendor/material-color-utilities');
const LIB = resolve(REPO, 'plugin/lib');
const MCU_OUT = resolve(LIB, 'mcu');

/**
 * Modules copied into the bundle.
 *
 * The whole vendored tree is copied rather than a curated subset: `index.js`
 * re-exports every folder, so trimming it would mean editing a third-party
 * entry point. It is Host-only code (never shipped to the browser) and the
 * complete tree is ~340 KB, which is cheaper than a hand-maintained subset that
 * silently breaks when a transitive import appears.
 */
const KEEP = [
  'index.js',
  'LICENSE',
  'blend',
  'contrast',
  'dislike',
  'dynamiccolor',
  'hct',
  'palettes',
  'quantize',
  'scheme',
  'score',
  'temperature',
  'utils',
];

/** Read a module and rewrite its specifiers so they resolve inside `plugin/lib`. */
function rewriteSpecifiers(source, moduleResolver) {
  return source.replace(
    /(\bfrom\s*|\bimport\s*\(\s*)(['"])(\.\.?\/[^'"]+)\2/gu,
    (whole, head, quote, specifier) => {
      const resolved = moduleResolver(specifier);
      return resolved === null ? whole : head + quote + resolved + quote;
    },
  );
}

async function main() {
  await rm(MCU_OUT, { recursive: true, force: true });
  await mkdir(MCU_OUT, { recursive: true });

  // 1. Copy the library verbatim. It is already the "patched" build with `.js`
  //    on every relative import; `build/vendor-mcu.mjs` produced that.
  for (const name of KEEP) {
    await cp(resolve(VENDOR, name), resolve(MCU_OUT, name), { recursive: true });
  }

  await writeFile(
    resolve(MCU_OUT, 'package.json'),
    JSON.stringify(
      {
        name: 'material-color-utilities-vendored',
        version: '0.4.0',
        private: true,
        type: 'module',
        main: 'index.js',
        license: 'Apache-2.0',
      },
      null,
      2,
    ) + '\n',
    'utf8',
  );

  // 2. Emit the palette module: the spec's role table, the engine, and the MCU
  //    namespace it is built over.
  const spec = await readFile(resolve(REPO, 'src/parts/palette-spec.js'), 'utf8');
  const engine = await readFile(resolve(REPO, 'src/parts/palette-engine.js'), 'utf8');

  const strip = (source) =>
    source
      .replace(/^\s*import\s[\s\S]*?;\s*$/gmu, '')
      .replace(/^export\s+(?=(?:const|let|var|function|class|async)\b)/gmu, '');

  const palette = `/**
 * Palette engine for the Host half — generated by build/bundle-host.mjs.
 *
 * Concatenates three things that have to agree: the role table, the engine and
 * the Material Color Utilities namespace the engine is constructed over.
 * Regenerate with:
 *
 *   node build/bundle-host.mjs
 */

import * as mcu from './mcu/index.js';

${strip(spec)}

${strip(engine)}

export { createPaletteEngine, ROLE_ORDER, FIXED_ROLE_ORDER, PRESETS, DEFAULT_PRESET };
export { mcu };
`;

  await mkdir(LIB, { recursive: true });
  await writeFile(resolve(LIB, 'palette.js'), palette, 'utf8');

  const bytes = Buffer.byteLength(palette, 'utf8');
  console.log(`wrote ${resolve(LIB, 'mcu')}/ (${KEEP.length} entries)`);
  console.log(`wrote ${resolve(LIB, 'palette.js')} (${bytes} bytes)`);
}

await main();
